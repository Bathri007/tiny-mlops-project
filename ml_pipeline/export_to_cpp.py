#!/usr/bin/env python3
"""
Stage 3 of the TinyMLOps pipeline: C++ code generation for the ESP32 firmware.

  artifacts/model_qat_int8.tflite -> firmware_esp32/src/model_data.h
      alignas(16) const unsigned char g_mnist_model_data[] = {...};
      const unsigned int g_mnist_model_data_len = N;
      + SHA-256 / timestamp / accuracy / quantization metadata

  artifacts/golden_vectors.json   -> firmware_esp32/src/test_vectors.h
      const int8_t  kTestImages[10][784];
      const uint8_t kTestLabels[10];
      const int8_t  kExpectedLogits[10][10];   (TFLite reference output, for bit-exact parity)
      kInputScale, kInputZeroPoint, kOutputScale, kOutputZeroPoint

The script refuses to generate code for a model whose SHA-256 does not match the
golden vectors (i.e. a model that has not passed evaluate_and_gate.py).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path
from typing import Any, Dict, Optional

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONFIG = REPO_ROOT / "ml_pipeline" / "config.yaml"
IMAGE_SIZE = 28 * 28


def load_config(path: str | Path = DEFAULT_CONFIG) -> Dict[str, Any]:
    with open(path, "r", encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def resolve(path: str | Path) -> Path:
    p = Path(path)
    return p if p.is_absolute() else REPO_ROOT / p


def _utc_now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def format_byte_array(data: bytes, per_line: int = 12) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + per_line]) + ",")
    return "\n".join(lines)


def format_int_rows(values, per_line: int = 28, width: int = 4) -> str:
    vals = list(values)
    rows = []
    for i in range(0, len(vals), per_line):
        rows.append("        " + ",".join(f"{v:>{width}d}" for v in vals[i : i + per_line]) + ",")
    return "\n".join(rows)


def generate_model_header(model_bytes: bytes, meta: Optional[Dict[str, Any]] = None,
                          generated_at: Optional[str] = None) -> str:
    meta = meta or {}
    digest = hashlib.sha256(model_bytes).hexdigest()
    ts = generated_at or _utc_now()
    acc = meta.get("int8_accuracy")
    fp32 = meta.get("fp32_accuracy")
    acc_str = f"{100 * acc:.2f}%" if acc is not None else "n/a"
    fp32_str = f"{100 * fp32:.2f}%" if fp32 is not None else "n/a"
    ops = ", ".join(meta.get("operators", [])) or "n/a"
    return f"""// =============================================================================
//  AUTO-GENERATED by ml_pipeline/export_to_cpp.py  --  DO NOT EDIT BY HAND
// =============================================================================
//  Model          : MNIST tiny CNN, QAT full-integer INT8 (TFLite flatbuffer)
//  Source         : artifacts/model_qat_int8.tflite
//  Size           : {len(model_bytes)} bytes ({len(model_bytes) / 1024:.2f} KiB)
//  SHA-256        : {digest}
//  Generated (UTC): {ts}
//  INT8 accuracy  : {acc_str} on MNIST test set (FP32 baseline {fp32_str})
//  Operators      : {ops}
//  Input  tensor  : int8 [1,28,28,1] scale={meta.get('input_scale', 'n/a')} zero_point={meta.get('input_zero_point', 'n/a')}
//  Output tensor  : int8 [1,10]      scale={meta.get('output_scale', 'n/a')} zero_point={meta.get('output_zero_point', 'n/a')}
// =============================================================================
#ifndef TINYMLOPS_MODEL_DATA_H_
#define TINYMLOPS_MODEL_DATA_H_

#include <stdint.h>

#define TINYMLOPS_MODEL_SHA256 "{digest}"
#define TINYMLOPS_MODEL_GENERATED_AT "{ts}"

constexpr char kModelSha256[] = TINYMLOPS_MODEL_SHA256;
constexpr char kModelGeneratedAt[] = TINYMLOPS_MODEL_GENERATED_AT;
constexpr float kModelInt8Accuracy = {acc if acc is not None else -1.0:.6f}f;

// 16-byte alignment is required by TFLite Micro for flatbuffer tensor data.
alignas(16) const unsigned char g_mnist_model_data[] = {{
{format_byte_array(model_bytes)}
}};
const unsigned int g_mnist_model_data_len = {len(model_bytes)};

#endif  // TINYMLOPS_MODEL_DATA_H_
"""


def generate_vectors_header(golden: Dict[str, Any], generated_at: Optional[str] = None) -> str:
    vecs = golden["vectors"]
    if len(vecs) != 10:
        raise ValueError(f"expected 10 golden vectors, got {len(vecs)}")
    for v in vecs:
        if len(v["image_int8"]) != IMAGE_SIZE:
            raise ValueError(f"vector {v['label']} has {len(v['image_int8'])} values, expected {IMAGE_SIZE}")
        if any(x < -128 or x > 127 for x in v["image_int8"]):
            raise ValueError("image values out of int8 range")
    ts = generated_at or _utc_now()
    images = "\n".join(
        f"    {{  // [{i}] digit {v['label']} (MNIST test index {v['test_index']})\n"
        f"{format_int_rows(v['image_int8'])}\n    }},"
        for i, v in enumerate(vecs)
    )
    logits = "\n".join(
        f"    {{{', '.join(f'{x:4d}' for x in v['expected_logits_int8'])}}},  // digit {v['label']}" for v in vecs
    )
    labels = ", ".join(str(v["label"]) for v in vecs)
    indices = ", ".join(str(v["test_index"]) for v in vecs)
    return f"""// =============================================================================
//  AUTO-GENERATED by ml_pipeline/export_to_cpp.py  --  DO NOT EDIT BY HAND
// =============================================================================
//  10 golden MNIST test images (one per digit), already quantized to INT8 with
//  the model's input scale/zero-point, plus the INT8 logits produced by the
//  TFLite reference interpreter on the host -> used for on-device BIST and
//  bit-exact host/device parity.
//  Model SHA-256  : {golden.get('model_sha256', 'n/a')}
//  Selection rule : {golden.get('selection', 'n/a')}
//  Test indices   : {indices}
//  Generated (UTC): {ts}
// =============================================================================
#ifndef TINYMLOPS_TEST_VECTORS_H_
#define TINYMLOPS_TEST_VECTORS_H_

#include <stdint.h>

constexpr int kNumTestVectors = 10;
constexpr int kImageSize = {IMAGE_SIZE};
constexpr int kNumClasses = 10;

constexpr float kInputScale = {float(golden['input_scale']):.9g}f;
constexpr int kInputZeroPoint = {int(golden['input_zero_point'])};
constexpr float kOutputScale = {float(golden['output_scale']):.9g}f;
constexpr int kOutputZeroPoint = {int(golden['output_zero_point'])};

#define TINYMLOPS_VECTORS_MODEL_SHA256 "{golden.get('model_sha256', '')}"

const uint8_t kTestLabels[kNumTestVectors] = {{{labels}}};

const int8_t kExpectedLogits[kNumTestVectors][kNumClasses] = {{
{logits}
}};

const int8_t kTestImages[kNumTestVectors][kImageSize] = {{
{images}
}};

#endif  // TINYMLOPS_TEST_VECTORS_H_
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=str(DEFAULT_CONFIG))
    ap.add_argument("--model", help="override INT8 .tflite path")
    ap.add_argument("--golden", help="override golden vectors JSON path")
    ap.add_argument("--out-dir", help="override output directory for the headers")
    args = ap.parse_args(argv)

    cfg = load_config(args.config)
    model_path = Path(args.model) if args.model else resolve(cfg["paths"]["int8_tflite"])
    golden_path = Path(args.golden) if args.golden else resolve(cfg["paths"]["golden_vectors_json"])
    out_dir = Path(args.out_dir) if args.out_dir else resolve(cfg["paths"]["firmware_src_dir"])
    gate_path = resolve(cfg["paths"]["gate_report_json"])

    print("=" * 72)
    print(" TinyMLOps | Stage 3: TFLite flatbuffer -> C++ headers")
    print("=" * 72)
    if not model_path.exists() or not golden_path.exists():
        print("[error] model or golden vectors missing - run `make train gate` first")
        return 1

    model_bytes = model_path.read_bytes()
    golden = json.loads(golden_path.read_text(encoding="utf-8"))
    digest = hashlib.sha256(model_bytes).hexdigest()
    if golden.get("model_sha256") and golden["model_sha256"] != digest:
        print(f"[error] golden vectors belong to model {golden['model_sha256'][:12]}..., "
              f"but {model_path.name} is {digest[:12]}... -> re-run the quality gate")
        return 1

    meta: Dict[str, Any] = {
        "input_scale": golden["input_scale"], "input_zero_point": golden["input_zero_point"],
        "output_scale": golden["output_scale"], "output_zero_point": golden["output_zero_point"],
    }
    if gate_path.exists():
        rep = json.loads(gate_path.read_text(encoding="utf-8"))
        if not rep.get("passed", False):
            print("[error] gate_report.json says the model FAILED its quality gates - refusing to export")
            return 1
        meta["int8_accuracy"] = rep["metrics"]["int8_tflite_accuracy"]
        meta["fp32_accuracy"] = rep["metrics"]["fp32_tflite_accuracy"]
        meta["operators"] = rep.get("operators", [])

    ts = _utc_now()
    out_dir.mkdir(parents=True, exist_ok=True)
    model_h = out_dir / "model_data.h"
    vectors_h = out_dir / "test_vectors.h"
    model_h.write_text(generate_model_header(model_bytes, meta, ts), encoding="utf-8", newline="\n")
    vectors_h.write_text(generate_vectors_header(golden, ts), encoding="utf-8", newline="\n")
    print(f"[cpp] {model_h} ({len(model_bytes):,} model bytes, sha256={digest[:16]}...)")
    print(f"[cpp] {vectors_h} (10 x 784 int8 images, labels {[v['label'] for v in golden['vectors']]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())

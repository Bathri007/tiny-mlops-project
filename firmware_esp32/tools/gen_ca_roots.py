#!/usr/bin/env python3
"""Generate firmware_esp32/src/ca_roots.h: the root CAs the ESP32 trusts for model downloads.

GitHub release downloads involve two hosts (checked 2026-11-27 with `openssl s_client`):
  github.com                            -> Sectigo ... -> USERTrust ECC Certification Authority
  release-assets/objects.githubusercontent.com -> Let's Encrypt ... -> ISRG Root X1
A few related roots are included too, so a routine CA rotation by GitHub does not break updates.
Certificates are taken from the Mozilla bundle shipped in `certifi` - nothing is typed by hand.

    python firmware_esp32/tools/gen_ca_roots.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import certifi

ROOTS = [
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "ISRG Root X1",
    "ISRG Root X2",
    "DigiCert Global Root G2",
]
OUT = Path(__file__).resolve().parents[1] / "src" / "ca_roots.h"


def main() -> int:
    bundle = Path(certifi.where()).read_text(encoding="ascii")
    # certifi's cacert.pem: "# Label: \"<name>\"" comment lines precede each PEM block
    blocks = re.findall(r'# Label: "([^"]+)".*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)', bundle, re.S)
    by_name = {name: pem for name, pem in blocks}
    missing = [r for r in ROOTS if r not in by_name]
    if missing:
        print(f"[error] not in certifi {certifi.__version__}: {missing}")
        return 1
    parts = []
    for name in ROOTS:
        lines = by_name[name].strip().splitlines()
        parts.append(f"// {name}\n" + "\n".join(f'"{l}\\n"' for l in lines))
    OUT.write_text(
        "// AUTO-GENERATED by firmware_esp32/tools/gen_ca_roots.py from certifi "
        f"{certifi.__version__} -- DO NOT EDIT\n"
        "// Root CAs trusted for HTTPS model downloads (GitHub Releases).\n"
        "#ifndef TINYMLOPS_CA_ROOTS_H_\n#define TINYMLOPS_CA_ROOTS_H_\n\n"
        "static const char kCaRoots[] =\n" + "\n".join(parts) + ";\n\n#endif  // TINYMLOPS_CA_ROOTS_H_\n",
        encoding="ascii", newline="\n")
    print(f"[ok] wrote {OUT} with {len(ROOTS)} roots")
    return 0


if __name__ == "__main__":
    sys.exit(main())
